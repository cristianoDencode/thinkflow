const tmp = (prefix: string) => fs.mkdtempSync(path.join(os.tmpdir(), prefix));

interface CliSetup {
  gateway: NotebookLmCliGateway;
  config: MemoryNotebookLmConfig;
  workDir: string;
  logFile: string;
  cleanup(): void;
}

function makeCli(
  knobs: Record<string, string> = {},
  opts: {
    config?: ConstructorParameters<typeof MemoryNotebookLmConfig>[0];
    minGapMs?: number;
    now?: () => number;
    env?: NodeJS.ProcessEnv;
  } = {},
): CliSetup {
  const workDir = tmp('thinkflow-nlm-work-');
  const logFile = path.join(workDir, '..', `${path.basename(workDir)}.log`);
  const config = new MemoryNotebookLmConfig({
    cliCommand: fakeCliCommand({ log: logFile, ...knobs }),
    ...opts.config,
  });
  const gateway = new NotebookLmCliGateway({
    config,
    workDir,
    minGapMs: opts.minGapMs ?? 0,
    killGraceMs: 0,
    now: opts.now,
    env: opts.env ?? { PATH: process.env.PATH ?? '', HOME: workDir },
  });
  return {
    gateway,
    config,
    workDir,
    logFile,
    cleanup: () => {
      fs.rmSync(workDir, { recursive: true, force: true });
      fs.rmSync(logFile, { force: true });
    },
  };
}

runGatewayContract('in-memory fake', () => ({
  gateway: new FakeNotebookLmGateway(),
  cleanup: () => undefined,
}));

runGatewayContract('CLI gateway + fake CLI', () => {
  const cli = makeCli();
  return { gateway: cli.gateway, cleanup: cli.cleanup };
});

describe('NotebookLmCliGateway', () => {
  let cli: CliSetup;
  afterEach(() => cli?.cleanup());

  it('passes the decrypted credentials and a minimal environment, never the parent secrets', async () => {
    process.env.THINKFLOW_TEST_LEAK = 'super-secret';
    try {
      cli = makeCli(
        {},
        { env: { ...process.env, PATH: process.env.PATH ?? '', ANTHROPIC_API_KEY: 'sk-leak' } },
      );
      await cli.gateway.createNotebook('Teste');
      const [start] = starts(readFakeCliLog(cli.logFile));
      expect(start!.hasAuthEnv).toBe(true);
      expect(start!.marker).toBe('fake-cookie-value');
      expect(start!.home).toBe(cli.workDir);
      const keys = start!.envKeys!;
      expect(keys).toContain('NOTEBOOKLM_AUTH_JSON');
      expect(keys).toContain('NOTEBOOKLM_HOME');
      expect(keys).not.toContain('THINKFLOW_TEST_LEAK');
      expect(keys).not.toContain('ANTHROPIC_API_KEY');
      expect(keys).not.toContain('THINKFLOW_SECRET');
    } finally {
      delete process.env.THINKFLOW_TEST_LEAK;
    }
  });

  it('sends the question through a temp file (never argv) and deletes it', async () => {
    cli = makeCli();
    const question = 'pergunta confidencial sobre salários';
    await cli.gateway.ask('nb_1', question, { timeoutMs: 10_000 });
    const log = readFakeCliLog(cli.logFile);
    const ask = starts(log).find((e) => e.argv?.[0] === 'ask')!;
    expect(JSON.stringify(ask.argv)).not.toContain('confidencial');
    expect(ask.argv).toContain('--prompt-file');
    expect(ask.argv).toContain('--new');
    expect(ask.argv).toContain('--json');
    const detail = log.find((e) => e.event === 'ask')!;
    expect(detail.promptFileExisted).toBe(true);
    expect(detail.questionLength).toBe(question.length);
    expect(fs.readdirSync(path.join(cli.workDir, 'tmp'))).toEqual([]);
  });

  it('adds file sources from bytes through a temp copy that is removed afterwards', async () => {
    cli = makeCli();
    const { sourceId } = await cli.gateway.addSource('nb_1', {
      bytes: new TextEncoder().encode('xyz'),
      fileName: 'doc-1.pdf',
      title: 'Relatório 2026.pdf',
      mimeType: 'application/pdf',
    });
    expect(sourceId).toMatch(/^src_/);
    const detail = readFakeCliLog(cli.logFile).find((e) => e.event === 'source-add')!;
    expect(detail).toMatchObject({
      title: 'Relatório 2026.pdf',
      mime: 'application/pdf',
      type: 'file',
      size: 3,
      fileName: 'doc-1.pdf',
    });
    expect(fs.readdirSync(path.join(cli.workDir, 'tmp'))).toEqual([]);
  });

  it('refuses a file name that was not generated by the app', async () => {
    cli = makeCli();
    const file = { bytes: new Uint8Array([1]), title: 't', mimeType: 'application/pdf' };
    for (const fileName of ['../x.pdf', 'Meu Arquivo.pdf', 'a/b.pdf']) {
      await expect(cli.gateway.addSource('nb_1', { ...file, fileName })).rejects.toThrow(
        'inválido',
      );
    }
  });

  it('maps CLI failures to error kinds', async () => {
    cli = makeCli();
    await expect(cli.gateway.ask('nb', '__GARBAGE__', { timeoutMs: 10_000 })).rejects.toMatchObject(
      { kind: 'bad_response' },
    );

    cli.config.set({ authJson: fakeStorageState('expired-cookie') });
    await expect(cli.gateway.createNotebook('x')).rejects.toMatchObject({ kind: 'auth' });
    const check = await cli.gateway.check();
    expect(check.ok).toBe(false);
    expect(check.message).toContain('expiradas');

    cli.config.set({ authJson: null });
    await expect(cli.gateway.createNotebook('x')).rejects.toMatchObject({ kind: 'not_configured' });
    expect(await cli.gateway.check()).toMatchObject({ ok: false });
  });

  it('reports a missing CLI', async () => {
    cli = makeCli({}, { config: { cliCommand: '/nonexistent/notebooklm' } });
    await expect(cli.gateway.createNotebook('x')).rejects.toMatchObject({ kind: 'cli_missing' });
    expect(await cli.gateway.check()).toMatchObject({ ok: false });
  });

  it('kills a hung process when the timeout elapses', async () => {
    cli = makeCli();
    const started = Date.now();
    await expect(cli.gateway.ask('nb', '__TIMEOUT__', { timeoutMs: 300 })).rejects.toMatchObject({
      kind: 'timeout',
    });
    expect(Date.now() - started).toBeLessThan(5000);
    const pid = starts(readFakeCliLog(cli.logFile)).at(-1)!.pid;
    await new Promise((r) => setTimeout(r, 100));
    expect(() => process.kill(pid, 0)).toThrow();
  });

  it('aborts on request', async () => {
    cli = makeCli();
    const controller = new AbortController();
    const pending = cli.gateway.ask('nb', '__TIMEOUT__', {
      timeoutMs: 30_000,
      signal: controller.signal,
    });
    setTimeout(() => controller.abort(), 200);
    await expect(pending).rejects.toMatchObject({ kind: 'timeout' });
  });

  it('maps source wait outcomes', async () => {
    cli = makeCli({ wait: 'timeout' });
    await expect(cli.gateway.waitSourceReady('nb', 'src', 2000)).rejects.toMatchObject({
      kind: 'timeout',
    });
    cli.cleanup();
    cli = makeCli({ wait: 'error' });
    await expect(cli.gateway.waitSourceReady('nb', 'src', 2000)).rejects.toMatchObject({
      kind: 'unavailable',
      message: expect.stringContaining('processing failed') as unknown as string,
    });
  });

  it('turns a "source limit reached" failure into a clear error carrying the limit', async () => {
    const file = {
      bytes: new Uint8Array([1]),
      fileName: 'doc1.txt',
      title: 'a',
      mimeType: 'text/plain',
    };
    cli = makeCli({ add: 'limit' });
    await expect(cli.gateway.addSource('nb', file)).rejects.toMatchObject({
      kind: 'source_limit',
      limit: 300,
      message: 'A conta do NotebookLM permite no máximo 300 fontes por notebook',
    });
    cli.cleanup();
    cli = makeCli({ add: 'limit-no-number' });
    await expect(cli.gateway.addSource('nb', file)).rejects.toMatchObject({
      kind: 'source_limit',
      limit: null,
    });
  });

  it('runs one CLI process at a time', async () => {
    cli = makeCli();
    await Promise.all([
      cli.gateway.ask('nb', '__SLOW__ 1', { timeoutMs: 10_000 }),
      cli.gateway.ask('nb', '__SLOW__ 2', { timeoutMs: 10_000 }),
      cli.gateway.ask('nb', '__SLOW__ 3', { timeoutMs: 10_000 }),
    ]);
    const log = readFakeCliLog(cli.logFile);
    const spans = starts(log).map((s) => ({
      start: s.at,
      end: log.find((e) => e.event === 'end' && e.pid === s.pid)!.at,
    }));
    expect(spans).toHaveLength(3);
    spans.sort((a, b) => a.start - b.start);
    for (let i = 1; i < spans.length; i++) {
      expect(spans[i]!.start).toBeGreaterThanOrEqual(spans[i - 1]!.end);
    }
  });

  it('spaces consecutive calls', async () => {
    cli = makeCli({}, { minGapMs: 250 });
    await cli.gateway.createNotebook('a');
    await cli.gateway.createNotebook('b');
    const log = readFakeCliLog(cli.logFile);
    const [first, second] = starts(log);
    const firstEnd = log.find((e) => e.event === 'end' && e.pid === first!.pid)!.at;
    expect(second!.at - firstEnd).toBeGreaterThanOrEqual(240);
  });

  describe('credential renewal', () => {
    const HOUR = 3_600_000;

    it('refreshes stale credentials before the call, through a temp file and without the env var', async () => {
      const now = 2_000_000_000_000;
      cli = makeCli({}, { now: () => now, config: { credentialsUpdatedAt: now - 13 * HOUR } });
      await cli.gateway.createNotebook('x');
      const log = starts(readFakeCliLog(cli.logFile));
      expect(log.map((e) => e.argv?.slice(0, 3).join(' '))).toEqual([
        'auth refresh --verify',
        'create --json --',
      ]);
      const refresh = log[0]!;
      expect(refresh.storage).toBe(true); // credentials came from a temp --storage file
      expect(log[1]!.storage).toBe(false);
      expect(refresh.hasAuthEnv).toBe(false);
      expect(refresh.envKeys).not.toContain('NOTEBOOKLM_AUTH_JSON');
      // the call itself uses the refreshed credentials
      expect(log[1]!.marker).toMatch(/^fake-refreshed-/);
      const stored = cli.config.get();
      expect(JSON.parse(stored.authJson!).cookies[0].value).toMatch(/^fake-refreshed-/);
      expect(stored.credentialsUpdatedAt).toBe(now);
      // the plaintext temp file is gone
      expect(fs.readdirSync(path.join(cli.workDir, 'tmp'))).toEqual([]);
    });

    it('does not refresh fresh credentials', async () => {
      const now = 2_000_000_000_000;
      cli = makeCli({}, { now: () => now, config: { credentialsUpdatedAt: now - 1 * HOUR } });
      await cli.gateway.createNotebook('x');
      expect(starts(readFakeCliLog(cli.logFile))).toHaveLength(1);
    });

    it('keeps going when the automatic renewal fails, and does not retry right away', async () => {
      const now = 2_000_000_000_000;
      cli = makeCli(
        { refresh: 'fail' },
        { now: () => now, config: { credentialsUpdatedAt: now - 13 * HOUR } },
      );
      await expect(cli.gateway.createNotebook('x')).resolves.toMatchObject({
        id: expect.any(String),
      });
      await cli.gateway.createNotebook('y');
      const refreshes = starts(readFakeCliLog(cli.logFile)).filter((e) => e.storage);
      expect(refreshes).toHaveLength(1);
      expect(cli.config.get().authJson).toBe(fakeStorageState());
      expect(fs.readdirSync(path.join(cli.workDir, 'tmp'))).toEqual([]);
    });

    it('refreshCredentials renews on demand and surfaces failures', async () => {
      cli = makeCli();
      await cli.gateway.refreshCredentials();
      expect(JSON.parse(cli.config.get().authJson!).cookies[0].value).toMatch(/^fake-refreshed-/);
      cli.cleanup();

      cli = makeCli({ refresh: 'fail' });
      await expect(cli.gateway.refreshCredentials()).rejects.toMatchObject({ kind: 'auth' });
    });
  });
});

describe('classifyFailure', () => {
  it.each([
    ['RATE_LIMITED', '', 'rate_limited'],
    ['AUTH_REQUIRED', '', 'auth'],
    [undefined, 'HTTP 429 Too Many Requests', 'rate_limited'],
    [undefined, 'Missing required cookies: __Secure-1PSIDTS', 'auth'],
    [undefined, 'Session expired, please login', 'auth'],
    ['NETWORK_ERROR', 'connection reset', 'unavailable'],
    ['VALIDATION_ERROR', 'Notebook has reached the source limit (300 sources)', 'source_limit'],
    [undefined, 'Cannot add source: maximum number of sources exceeded', 'source_limit'],
    ['RATE_LIMITED', 'daily source import quota reached', 'rate_limited'],
  ])('%s / %s -> %s', (code, text, kind) => {
    expect(classifyFailure(code, text)).toBe(kind);
  });
});

describe('DisabledNotebookLmGateway', () => {
  it('reports not_configured everywhere', async () => {
    const gateway = new DisabledNotebookLmGateway();
    expect(await gateway.check()).toMatchObject({ ok: false });
    await expect(gateway.createNotebook()).rejects.toBeInstanceOf(NotebookLmError);
    await expect(gateway.ask()).rejects.toMatchObject({ kind: 'not_configured' });
    await expect(gateway.refreshCredentials()).rejects.toMatchObject({ kind: 'not_configured' });
  });
});

describe('sweepNotebookLmScratch', () => {
  let dir: string;
  beforeEach(() => {
    dir = tmp('thinkflow-nlm-sweep-');
  });
  afterEach(() => fs.rmSync(dir, { recursive: true, force: true }));

  it('removes leftovers but keeps other files', () => {
    fs.mkdirSync(path.join(dir, 'tmp'));
    fs.mkdirSync(path.join(dir, 'login-abc'));
    fs.writeFileSync(path.join(dir, 'login-abc', 'storage_state.json'), 'x');
    fs.mkdirSync(path.join(dir, 'profiles'));
    sweepNotebookLmScratch(dir);
    expect(fs.readdirSync(dir)).toEqual(['profiles']);
    expect(() => sweepNotebookLmScratch(path.join(dir, 'nope'))).not.toThrow();
  });
});
